-- DDL de referencia para una base vacía con el modelo JPA actualmente implementado.
-- No es una migración automática: Flyway no está configurado en la aplicación.
-- No aplicar directamente a una base existente sin revisar y respaldar su esquema.

CREATE TABLE IF NOT EXISTS agricultor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    ubicacion_valle VARCHAR(255) NOT NULL,
    cedula VARCHAR(255) NOT NULL,
    CONSTRAINT uk_agricultor_cedula UNIQUE (cedula)
);

CREATE TABLE IF NOT EXISTS transportista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    cedula VARCHAR(20) NOT NULL,
    CONSTRAINT uk_transportista_cedula UNIQUE (cedula)
);

CREATE TABLE IF NOT EXISTS vehiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(7) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    capacidad_kg INTEGER NOT NULL CHECK (capacidad_kg > 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    agricultor_id BIGINT,
    transportista_id BIGINT,
    CONSTRAINT uk_vehiculo_placa UNIQUE (placa),
    CONSTRAINT ck_vehiculo_placa_formato
        CHECK (placa ~ '^[A-Z]{3}-[0-9]{3}$'),
    CONSTRAINT ck_vehiculo_propietario_exclusivo CHECK (
        (agricultor_id IS NOT NULL AND transportista_id IS NULL)
        OR (agricultor_id IS NULL AND transportista_id IS NOT NULL)
    ),
    CONSTRAINT fk_vehiculo_agricultor
        FOREIGN KEY (agricultor_id) REFERENCES agricultor (id),
    CONSTRAINT fk_vehiculo_transportista
        FOREIGN KEY (transportista_id) REFERENCES transportista (id)
);

CREATE INDEX IF NOT EXISTS idx_vehiculo_agricultor
    ON vehiculo (agricultor_id);
CREATE INDEX IF NOT EXISTS idx_vehiculo_transportista
    ON vehiculo (transportista_id);

CREATE TABLE IF NOT EXISTS orden_logistica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto VARCHAR(100) NOT NULL,
    peso_kg NUMERIC(12, 2) NOT NULL CHECK (peso_kg > 0),
    destino VARCHAR(100) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_ALISTAMIENTO'
        CHECK (estado IN ('PENDIENTE_ALISTAMIENTO', 'ALISTADO', 'EN_RUTA')),
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_salida DATE,
    guia_despacho VARCHAR(40) UNIQUE,
    agricultor_id BIGINT NOT NULL,
    vehiculo_id BIGINT,
    CONSTRAINT ck_orden_logistica_ruta_completa CHECK (
        (
            estado IN ('PENDIENTE_ALISTAMIENTO', 'ALISTADO')
            AND vehiculo_id IS NULL
            AND fecha_salida IS NULL
            AND guia_despacho IS NULL
        )
        OR (
            estado = 'EN_RUTA'
            AND vehiculo_id IS NOT NULL
            AND fecha_salida IS NOT NULL
            AND guia_despacho IS NOT NULL
        )
    ),
    CONSTRAINT fk_orden_logistica_agricultor
        FOREIGN KEY (agricultor_id) REFERENCES agricultor (id),
    CONSTRAINT fk_orden_logistica_vehiculo
        FOREIGN KEY (vehiculo_id) REFERENCES vehiculo (id)
);

CREATE INDEX IF NOT EXISTS idx_orden_logistica_estado
    ON orden_logistica (estado);
CREATE INDEX IF NOT EXISTS idx_orden_logistica_agricultor
    ON orden_logistica (agricultor_id);

CREATE TABLE IF NOT EXISTS transaccion_precio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto VARCHAR(100) NOT NULL,
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    fecha_transaccion TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_transaccion_precio_producto_fecha
    ON transaccion_precio (LOWER(producto), fecha_transaccion);

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    municipio VARCHAR(50) NOT NULL,
    cantidad NUMERIC(10, 2) NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    fecha_cosecha DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    agricultor_id BIGINT NOT NULL,
    CONSTRAINT productos_agricultor_id_fkey
        FOREIGN KEY (agricultor_id)
        REFERENCES agricultor (id)
);

CREATE INDEX IF NOT EXISTS idx_productos_filtro
    ON productos (municipio, categoria, estado);
