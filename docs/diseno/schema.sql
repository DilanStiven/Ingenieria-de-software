-- DDL de referencia para una base vacía con el modelo JPA actualmente implementado.
-- No es una migración automática: Flyway no está configurado en la aplicación.
-- No aplicar directamente a una base existente sin revisar y respaldar su esquema.

CREATE TABLE IF NOT EXISTS agricultor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    ubicacion_valle VARCHAR(255) NOT NULL,
    cedula VARCHAR(255) NOT NULL,
    CONSTRAINT uk_agricultor_cedula UNIQUE (cedula)
);

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    municipio VARCHAR(50) NOT NULL,
    cantidad NUMERIC(10, 2) NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    fecha_cosecha DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    agricultor_id BIGINT NOT NULL,
    CONSTRAINT productos_agricultor_id_fkey
        FOREIGN KEY (agricultor_id)
        REFERENCES agricultor (id)
);

CREATE INDEX IF NOT EXISTS idx_productos_filtro
    ON productos (municipio, categoria, estado);
