package com.agrovalle.agrovalle_connect.repositories;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;

class BilleteraMigrationTest {

    private static final String CLASSPATH_MIGRATIONS = "classpath:db/migration";
    private static final String DATABASE_USER = "sa";
    private static final String DATABASE_PASSWORD = "";
    private static final int VERSION_6 = 6;
    private static final String DATABASE_FRESH =
            "jdbc:h2:mem:hu11_fresh;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
    private static final String DATABASE_EXISTING =
            "jdbc:h2:mem:hu11_existing;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
    private static final BigDecimal CANTIDAD_LEGACY = new BigDecimal("1.00");

    @Test
    void aplicaMigracionesDesdeCeroHastaCrearBilletera() throws Exception {
        Flyway flyway = configurarFlyway(DATABASE_FRESH);

        flyway.migrate();

        assertEquals("19", flyway.info().current().getVersion().getVersion());
        assertEquals(1, contarTabla(DATABASE_FRESH, "BILLETERA"));
        assertEquals(1, contarTabla(DATABASE_FRESH, "NOTIFICACION"));
        assertEquals(1, contarTabla(DATABASE_FRESH, "ORDEN_LOGISTICA"));
        assertEquals(1, contarTabla(DATABASE_FRESH, "RESENA"));
        assertEquals(1, contarColumna(DATABASE_FRESH, "AGRICULTOR", "CORREO"));
        assertEquals(1, contarColumna(DATABASE_FRESH, "AGRICULTOR", "PASSWORD_HASH"));
        assertEquals(1, contarColumna(DATABASE_FRESH, "RESENA", "ESTRELLAS"));
        assertEquals(1, contarColumna(DATABASE_FRESH, "RESENA", "COMENTARIO"));
        assertEquals(1, contarColumna(DATABASE_FRESH, "AGRICULTOR",
                "CALIFICACION_PROMEDIO"));
    }

    @Test
    void actualizaEsquemaExistenteSinRecrearAgricultores() throws Exception {
        try (Connection conexion = DriverManager.getConnection(
                DATABASE_EXISTING, DATABASE_USER, DATABASE_PASSWORD);
                Statement sentencia = conexion.createStatement()) {
            sentencia.execute("""
                    CREATE TABLE agricultor (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre VARCHAR(255) NOT NULL,
                        ubicacion_valle VARCHAR(255) NOT NULL,
                        cedula VARCHAR(20) NOT NULL UNIQUE
                    )
                    """);
            sentencia.execute("""
                    INSERT INTO agricultor (nombre, ubicacion_valle, cedula)
                    VALUES ('Agricultor de prueba', 'Valle', '123456')
                    """);
            sentencia.execute("""
                    CREATE TABLE pedido (
                        id BIGINT PRIMARY KEY,
                        id_producto BIGINT NOT NULL
                    )
                    """);
            sentencia.execute("INSERT INTO pedido (id, id_producto) VALUES (9, 3)");
            sentencia.execute("""
                    CREATE TABLE orden_compra (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                    """);
        }

        Flyway flyway = configurarFlyway(DATABASE_EXISTING);
        flyway.migrate();

        assertEquals("19", flyway.info().current().getVersion().getVersion());
        assertEquals(1, contarAgricultores(DATABASE_EXISTING));
        assertEquals(1, contarCredencialesLegadasNulas(DATABASE_EXISTING));
        assertEquals(1, contarTabla(DATABASE_EXISTING, "BILLETERA"));
        assertEquals(1, contarTabla(DATABASE_EXISTING, "NOTIFICACION"));
        assertEquals(1, contarTabla(DATABASE_EXISTING, "ORDEN_LOGISTICA"));
        assertEquals(CANTIDAD_LEGACY, obtenerCantidadPedido(DATABASE_EXISTING, 9L));
    }

    private Flyway configurarFlyway(final String url) {
        return Flyway.configure()
                .dataSource(url, DATABASE_USER, DATABASE_PASSWORD)
                .locations(CLASSPATH_MIGRATIONS)
                .baselineOnMigrate(true)
                .baselineVersion(String.valueOf(VERSION_6))
                .load();
    }

    private int contarTabla(final String url, final String tabla) throws Exception {
        try (Connection conexion = DriverManager.getConnection(
                url, DATABASE_USER, DATABASE_PASSWORD);
                Statement sentencia = conexion.createStatement();
                ResultSet resultado = sentencia.executeQuery(
                        "SELECT COUNT(*) FROM information_schema.tables "
                                + "WHERE table_schema = 'PUBLIC' AND table_name = '" + tabla + "'")) {
            resultado.next();
            return resultado.getInt(1);
        }
    }

    private int contarAgricultores(final String url) throws Exception {
        try (Connection conexion = DriverManager.getConnection(
                url, DATABASE_USER, DATABASE_PASSWORD);
                Statement sentencia = conexion.createStatement();
                ResultSet resultado = sentencia.executeQuery(
                        "SELECT COUNT(*) FROM agricultor")) {
            resultado.next();
            return resultado.getInt(1);
        }
    }

    private int contarColumna(final String url, final String tabla, final String columna)
            throws Exception {
        try (Connection conexion = DriverManager.getConnection(
                url, DATABASE_USER, DATABASE_PASSWORD);
                Statement sentencia = conexion.createStatement();
                ResultSet resultado = sentencia.executeQuery(
                        "SELECT COUNT(*) FROM information_schema.columns "
                                + "WHERE table_schema = 'PUBLIC' AND table_name = '" + tabla
                                + "' AND column_name = '" + columna + "'")) {
            resultado.next();
            return resultado.getInt(1);
        }
    }

    private int contarCredencialesLegadasNulas(final String url) throws Exception {
        try (Connection conexion = DriverManager.getConnection(
                url, DATABASE_USER, DATABASE_PASSWORD);
                Statement sentencia = conexion.createStatement();
                ResultSet resultado = sentencia.executeQuery(
                        "SELECT COUNT(*) FROM agricultor "
                                + "WHERE correo IS NULL AND password_hash IS NULL")) {
            resultado.next();
            return resultado.getInt(1);
        }
    }

    private BigDecimal obtenerCantidadPedido(final String url, final long pedidoId)
            throws Exception {
        try (Connection conexion = DriverManager.getConnection(
                url, DATABASE_USER, DATABASE_PASSWORD);
                Statement sentencia = conexion.createStatement();
                ResultSet resultado = sentencia.executeQuery(
                        "SELECT cantidad FROM pedido WHERE id = " + pedidoId)) {
            resultado.next();
            return resultado.getBigDecimal(1);
        }
    }
}
