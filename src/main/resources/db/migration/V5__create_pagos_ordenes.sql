CREATE TABLE IF NOT EXISTS pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    monto NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    medio_pago VARCHAR(20) NOT NULL CHECK (medio_pago IN ('TARJETA', 'PSE')),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    referencia_pasarela VARCHAR(100),
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_pago_referencia UNIQUE (referencia_pasarela),
    CONSTRAINT fk_pago_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id)
);

CREATE INDEX IF NOT EXISTS idx_pago_pedido
    ON pago (id_pedido);

CREATE INDEX IF NOT EXISTS idx_pago_estado_fecha
    ON pago (estado, fecha_creacion);

CREATE TABLE IF NOT EXISTS orden_compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    id_pago BIGINT NOT NULL,
    numero_orden VARCHAR(40) NOT NULL,
    monto_total NUMERIC(12, 2) NOT NULL CHECK (monto_total > 0),
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_orden_compra_numero UNIQUE (numero_orden),
    CONSTRAINT uk_orden_compra_pago UNIQUE (id_pago),
    CONSTRAINT fk_orden_compra_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id),
    CONSTRAINT fk_orden_compra_pago
        FOREIGN KEY (id_pago) REFERENCES pago (id)
);

CREATE INDEX IF NOT EXISTS idx_orden_compra_pedido
    ON orden_compra (id_pedido);
