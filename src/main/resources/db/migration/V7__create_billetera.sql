CREATE TABLE IF NOT EXISTS billetera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agricultor_id BIGINT NOT NULL,
    saldo NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (saldo >= 0),
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_billetera_agricultor UNIQUE (agricultor_id),
    CONSTRAINT fk_billetera_agricultor
        FOREIGN KEY (agricultor_id) REFERENCES agricultor (id)
);

CREATE INDEX IF NOT EXISTS idx_billetera_agricultor
    ON billetera (agricultor_id);
