CREATE TABLE IF NOT EXISTS orden_logistica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto VARCHAR(100) NOT NULL,
    peso_kg NUMERIC(12, 2) NOT NULL,
    destino VARCHAR(100) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_salida DATE,
    guia_despacho VARCHAR(40),
    agricultor_id BIGINT NOT NULL REFERENCES agricultor (id),
    vehiculo_id BIGINT,
    pedido_id BIGINT REFERENCES pedido (id),
    CONSTRAINT uk_orden_logistica_guia UNIQUE (guia_despacho),
    CONSTRAINT ck_orden_logistica_peso_positivo CHECK (peso_kg > 0),
    CONSTRAINT ck_orden_logistica_ruta_completa CHECK (
        (estado IN ('PENDIENTE_ALISTAMIENTO', 'ALISTADO')
            AND vehiculo_id IS NULL AND fecha_salida IS NULL AND guia_despacho IS NULL)
        OR (estado = 'EN_RUTA'
            AND vehiculo_id IS NOT NULL AND fecha_salida IS NOT NULL AND guia_despacho IS NOT NULL)
    )
);

ALTER TABLE orden_logistica
    ADD COLUMN IF NOT EXISTS pedido_id BIGINT REFERENCES pedido (id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_orden_logistica_pedido
    ON orden_logistica (pedido_id);

CREATE INDEX IF NOT EXISTS idx_orden_logistica_estado
    ON orden_logistica (estado);

CREATE INDEX IF NOT EXISTS idx_orden_logistica_agricultor
    ON orden_logistica (agricultor_id);
