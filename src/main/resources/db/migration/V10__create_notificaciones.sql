CREATE TABLE notificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agricultor_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    mensaje TEXT NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notificacion_agricultor
        FOREIGN KEY (agricultor_id) REFERENCES agricultor (id)
);

CREATE INDEX idx_notificacion_agricultor_fecha
    ON notificacion (agricultor_id, fecha_creacion);
