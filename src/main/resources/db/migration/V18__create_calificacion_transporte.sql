CREATE TABLE IF NOT EXISTS calificacion_transporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viaje_id BIGINT NOT NULL,
    conductor_id BIGINT NOT NULL,
    puntualidad SMALLINT NOT NULL,
    estado_cajas VARCHAR(30) NOT NULL,
    fecha_calificacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_calificacion_transporte_viaje UNIQUE (viaje_id),
    CONSTRAINT ck_calificacion_transporte_puntualidad
        CHECK (puntualidad BETWEEN 1 AND 5),
    CONSTRAINT ck_calificacion_transporte_estado_cajas
        CHECK (BTRIM(estado_cajas) <> ''),
    CONSTRAINT fk_calificacion_transporte_viaje
        FOREIGN KEY (viaje_id) REFERENCES orden_logistica (id),
    CONSTRAINT fk_calificacion_transporte_conductor
        FOREIGN KEY (conductor_id) REFERENCES transportista (id)
);

CREATE INDEX IF NOT EXISTS idx_calificacion_transporte_conductor
    ON calificacion_transporte (conductor_id);
