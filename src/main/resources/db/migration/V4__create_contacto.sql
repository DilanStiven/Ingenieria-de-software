CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_PAGO',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_producto
        FOREIGN KEY (id_producto) REFERENCES productos (id)
);

CREATE INDEX idx_pedido_producto_estado
    ON pedido (id_producto, estado);

CREATE TABLE contacto_mensaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    mensaje TEXT NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_contacto_mensaje_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id)
);

CREATE INDEX idx_contacto_mensaje_pedido_fecha
    ON contacto_mensaje (id_pedido, fecha_creacion);
