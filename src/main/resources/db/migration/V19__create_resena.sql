CREATE TABLE IF NOT EXISTS resena (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra BIGINT NOT NULL,
    id_comprador BIGINT NOT NULL,
    id_agricultor BIGINT NOT NULL,
    estrellas INTEGER NOT NULL,
    comentario VARCHAR(1000),
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_resena_estrellas
        CHECK (estrellas BETWEEN 1 AND 5),
    CONSTRAINT uk_resena_orden
        UNIQUE (id_orden_compra),
    CONSTRAINT fk_resena_orden_compra
        FOREIGN KEY (id_orden_compra) REFERENCES orden_compra (id),
    CONSTRAINT fk_resena_agricultor
        FOREIGN KEY (id_agricultor) REFERENCES agricultor (id)
);

CREATE INDEX IF NOT EXISTS idx_resena_agricultor
    ON resena (id_agricultor);
